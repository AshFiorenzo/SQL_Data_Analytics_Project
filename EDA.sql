-- DATE EXPLORATION 
-- Identify the earliest and latest dates (boundaries).Understand the scope of data and the timespan.
-- find the date of first and last order 
select 
    min(order_date) as first_order_date, 
    max(order_date) as last_order_date,
    date_diff('year',min(order_date),max(order_date)) as total_year -- 'month' 'day' 
from gold.fact_sales;
--find the youngest and oldest customer 
select 
    min(birthday) as youngest_birthday,
    date_diff('year',max(birthday),CURRENT_DATE) as yountest_age,
    date_diff('year',min(birthday),CURRENT_DATE) as oldest_age,
    min(birthday) as oldest_birthday
from 
    gold.dim_customers;

