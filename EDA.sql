-- MAGNITUDE ANALYSIS 
-- compare the measure values by categories - [Measure] by [Dimension]
-- Find total customers by countries
select country, count(customer_key) as total_customers from gold.dim_customers group by country order by total_customers DESC;
-- Find total customers by gender
select gender, count(customer_key) as total_customers from gold.dim_customers group by gender order by total_customers DESC;
-- Find total products by category
select category, count(product_key) as total_products from gold.dim_products group by category;
-- What is the average costs in each category?
select category, avg(product_cost) as avgerage_cost from gold.dim_products group by category order by avgerage_cost DESC;
-- What is the total revenue generated for each category?
select dp.category, sum(fs.sales_amount) as total_revenue 
from  gold.fact_sales as fs left join gold.dim_products as dp on dp.product_key = fs.product_key
group by dp.category order by total_revenue DESC;
-- Find total revenue is generated by each customer
select dp.customer_key, dp.first_name, dp.last_name, sum(fs.sales_amount) as total_revenue 
from  gold.fact_sales as fs left join gold.dim_customers as dp on dp.customer_key = fs.customer_key
group by dp.customer_key, dp.first_name, dp.last_name order by total_revenue DESC;
-- What is the distribution of sold items across countries?
select dp.country, sum(fs.quantity) as total_sold_items 
from  gold.fact_sales as fs left join gold.dim_customers as dp on dp.customer_key = fs.customer_key
group by dp.country order by total_sold_items DESC;

-- RANKING ANALYSIS 
-- Top performers & bottom performers 
-- Which 5 products generate the highest revenue?
select 
    dp.product_key,
    dp.product_name,
    sum(fs.sales_amount) as total_revenue
from 
    gold.fact_sales as fs left join gold.dim_products as dp on fs.product_key = dp.product_key 
group by 
    dp.product_key, dp.product_name
order by 
    total_revenue DESC
limit 5;
-- with window functions
select * from (
select 
    dp.product_key,
    dp.product_name,
    sum(fs.sales_amount) as total_revenue,
    row_number() over (order by sum(fs.sales_amount) DESC) as row_number,
    rank() over (order by sum(fs.sales_amount) DESC) as rank,
from 
    gold.fact_sales as fs left join gold.dim_products as dp on fs.product_key = dp.product_key 
group by 
    dp.product_key, dp.product_name
) where rank <=5;
-- What are the 5 worst-performing products in terms of sales?
select 
    dp.product_key,
    dp.product_name,
    sum(fs.sales_amount) as total_revenue
from 
    gold.fact_sales as fs left join gold.dim_products as dp on fs.product_key = dp.product_key 
group by 
    dp.product_key, dp.product_name
order by 
    total_revenue
limit 5;
-- top 3 customers with most order placed 
